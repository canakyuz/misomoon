// Builds `deploy/` at the repo root: one folder with no workspace dependencies, which is
// what the Deploy to Cloudflare button needs. It holds the bundled Worker, the built
// dashboard, the migrations, a wrangler.jsonc, and a package.json whose `deploy` script
// migrates every bound database by binding name and then deploys. CI pushes this folder
// to the `deploy` branch (.github/workflows/deploy-branch.yml).  pnpm bundle
import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { parseJsonc, selfHostedVars } from './bundle-vars.ts'

const api = new URL('../', import.meta.url)
const out = new URL('../../../deploy/', import.meta.url)
const path = (u: URL) => decodeURIComponent(u.pathname)

const source = parseJsonc(readFileSync(new URL('wrangler.jsonc', api), 'utf8'))
const { version } = JSON.parse(readFileSync(new URL('package.json', api), 'utf8'))
const wranglerVersion = JSON.parse(readFileSync(new URL('node_modules/wrangler/package.json', api), 'utf8')).version

rmSync(out, { recursive: true, force: true })
mkdirSync(out)

// The Worker: wrangler bundles src/ and the core package into worker/index.js, and the
// tracker into a separate text module next to it.
execFileSync('wrangler', ['deploy', '--dry-run', '--outdir', path(new URL('worker', out))], { cwd: path(api), stdio: ['ignore', 'ignore', 'inherit'] })
for (const f of readdirSync(new URL('worker', out))) if (f.endsWith('.map') || f === 'README.md') rmSync(new URL(`worker/${f}`, out))
cpSync(new URL(source.assets.directory, api), new URL('public', out), { recursive: true, filter: (f) => !f.endsWith('.map') })
cpSync(new URL('migrations', api), new URL('migrations', out), { recursive: true })

const shards = source.d1_databases.filter((d: { binding: string }) => d.binding.startsWith('SHARD_'))
const config = {
	$schema: 'node_modules/wrangler/config-schema.json',
	name: 'misomoon',
	main: 'worker/index.js',
	no_bundle: true,
	find_additional_modules: true,
	base_dir: 'worker',
	rules: source.rules,
	compatibility_date: source.compatibility_date,
	compatibility_flags: source.compatibility_flags,
	observability: source.observability,
	assets: { ...source.assets, directory: 'public' },
	d1_databases: source.d1_databases,
	queues: source.queues,
	ratelimits: source.ratelimits,
	browser: source.browser,
	triggers: source.triggers,
	vars: selfHostedVars(source.vars),
}
const header = `// Generated by apps/api/scripts/bundle.ts from misomoon ${version}. Configuration: docs/configuration.md\n`
writeFileSync(new URL('wrangler.jsonc', out), header + JSON.stringify(config, null, '\t') + '\n')

writeFileSync(
	new URL('package.json', out),
	JSON.stringify(
		{
			name: 'misomoon',
			version,
			private: true,
			description: 'Privacy-first web analytics that runs in your Cloudflare account.',
			type: 'module',
			scripts: { deploy: 'node migrate.js && wrangler deploy' },
			devDependencies: { wrangler: wranglerVersion },
			cloudflare: { label: 'misomoon analytics', products: ['Workers', 'D1', 'Queues'] },
		},
		null,
		2,
	) + '\n',
)

writeFileSync(
	new URL('migrate.js', out),
	`// Applies migrations to CONTROL and to every SHARD_* database bound in wrangler.jsonc,
// by binding name, so it works whatever the databases are called.
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

const config = readFileSync(new URL('wrangler.jsonc', import.meta.url), 'utf8')
for (const [, binding] of config.matchAll(/"binding":\\s*"(CONTROL|SHARD_(?:(?:EU|US|APAC)_)?\\d+)"/g)) {
	console.log(\`migrating \${binding}\`)
	execFileSync('npx', ['wrangler', 'd1', 'migrations', 'apply', binding, '--remote'], { stdio: 'inherit' })
}
`,
)

writeFileSync(
	new URL('README.md', out),
	`# misomoon deploy bundle

This folder is built from [misomoon](https://github.com/jackzard/misomoon) ${version} by
\`pnpm bundle\`. Don't edit it. Change the source and build it again.

It deploys the misomoon Worker, its dashboard, ${shards.length + 1} D1 databases, and a queue
to your Cloudflare account:

\`\`\`sh
npm install
npm run deploy
\`\`\`

The self-hosting guide explains the setup after the first deploy:
https://github.com/jackzard/misomoon/blob/main/docs/self-hosting.md
`,
)

writeFileSync(new URL('.gitignore', out), 'node_modules\n.wrangler\n.dev.vars\n')
console.log(`deploy/ is ready: misomoon ${version}, ${shards.length} shards, wrangler ${wranglerVersion}`)
